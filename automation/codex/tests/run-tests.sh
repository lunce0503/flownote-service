#!/usr/bin/env bash
set -Eeuo pipefail

readonly AUTOMATION_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
readonly RUNNER="$AUTOMATION_ROOT/bin/flownote-codex-run"
readonly DISPATCHER="$AUTOMATION_ROOT/bin/flownote-codex-dispatch"
readonly FEEDBACK_COLLECTOR="$AUTOMATION_ROOT/bin/flownote-codex-feedback-collect"
readonly NOTIFIER="$AUTOMATION_ROOT/bin/flownote-codex-notify"
readonly INSTALLER="$AUTOMATION_ROOT/install.sh"
readonly TEST_ROOT="$(mktemp -d)"

PASS_COUNT=0
FAIL_COUNT=0

cleanup() {
  rm -rf -- "$TEST_ROOT"
}
trap cleanup EXIT

fail() {
  printf 'FAIL: %s\n' "$*" >&2
  return 1
}

assert_file() {
  [[ -f "$1" ]] || fail "expected file: $1"
}

assert_not_exists() {
  [[ ! -e "$1" ]] || fail "expected path to be absent: $1"
}

assert_contains() {
  local file="$1"
  local expected="$2"
  grep -F -- "$expected" "$file" >/dev/null || fail "expected '$expected' in $file"
}

assert_not_contains() {
  local file="$1"
  local unexpected="$2"
  if grep -F -- "$unexpected" "$file" >/dev/null; then
    fail "did not expect '$unexpected' in $file"
  fi
}

run_test() {
  local name="$1"
  shift

  set +e
  (
    set -Eeuo pipefail
    "$@"
  )
  local status=$?
  set -e

  if [[ "$status" -eq 0 ]]; then
    printf 'PASS: %s\n' "$name"
    PASS_COUNT=$((PASS_COUNT + 1))
  else
    printf 'FAIL: %s\n' "$name" >&2
    FAIL_COUNT=$((FAIL_COUNT + 1))
  fi
}

make_git_fixture() {
  local fixture="$1"
  local seed="$fixture/seed"
  local remote="$fixture/remote.git"
  local repository="$fixture/repository"

  mkdir -p "$fixture"
  git init --bare --quiet "$remote"
  git init --quiet --initial-branch=main "$seed"
  git -C "$seed" config user.name "Automation Test"
  git -C "$seed" config user.email "automation@example.invalid"

  printf '# fixture\n' > "$seed/README.md"
  git -C "$seed" add README.md
  git -C "$seed" commit --quiet -m "initial"
  git -C "$seed" remote add origin "$remote"
  git -C "$seed" push --quiet --set-upstream origin main
  git --git-dir="$remote" symbolic-ref HEAD refs/heads/main
  git clone --quiet --bare "$remote" "$repository"
  git -C "$repository" config remote.origin.fetch '+refs/heads/*:refs/remotes/origin/*'
  git -C "$repository" fetch --quiet --prune origin
  mkdir -p "$fixture/codex-home"
  printf '%s\n' 'model = "default-test-model"' > "$fixture/codex-home/config.toml"
  printf '%s\n' '{"auth_mode":"test"}' > "$fixture/codex-home/auth.json"
}

