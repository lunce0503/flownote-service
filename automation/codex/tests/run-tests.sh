  printf '%s\n' '{"sent":true,"recipient":"lunce0503@gmail.com","message_id":"fake-message-id"}' > "$output_file"
else
  printf '%s\n' \
    '{"status":"completed","summary":"fake result","findings":[],"validation":[],"changed_files":[],"deployment_performed":false}' \
    > "$output_file"
fi
printf '%s\n' '{"type":"turn.completed","usage":{"input_tokens":1,"output_tokens":1}}'
printf 'fake progress\n' >&2
exit "${FAKE_CODEX_EXIT_CODE:-0}"
FAKE_CODEX
  chmod 700 "$path"
}

