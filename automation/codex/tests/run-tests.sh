  local path="$1"

  mkdir -p "$(dirname "$path")"
  cat > "$path" <<'FAKE_CODEX'
#!/usr/bin/env bash
set -Eeuo pipefail

if [[ "${1:-}" == 'plugin' && "${2:-}" == 'list' ]]; then
  printf '%s\n' \
    'gmail@openai-curated-remote installed, enabled' \
    'google-drive@openai-curated-remote installed, enabled'
  exit 0
fi

printf '%s\n' "$@" > "${FAKE_CODEX_ARGS:?}"
cat > "${FAKE_CODEX_STDIN:?}"
env | sort > "${FAKE_CODEX_ENV:?}"

worktree=''
sandbox=''
output_file=''
output_schema=''

while (($#)); do
  case "$1" in
    -C)
      worktree="$2"
      shift 2
      ;;
    --sandbox)
      sandbox="$2"
      shift 2
      ;;
    --config)
      if [[ "$2" == *'extends=":workspace"'* ]]; then
        sandbox='workspace-write'
      fi
      shift 2
